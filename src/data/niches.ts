/** Находим нишу по тексту. Самое длинное совпадение побеждает: «ремонт авто» сильнее «ремонт» */
export function detectNiche(text: string): Niche | null {
  const t = ` ${text.toLowerCase().replace(/ё/g, 'е')} `
  let best: Niche | null = null
  let bestLen = 0
  for (const n of NICHES) {
    for (const k of n.keys) {
      const key = k.replace(/ё/g, 'е')
      if (key.length > bestLen && t.includes(key)) {
        best = n
        bestLen = key.length
      }
    }
  }
  return best
}

const CAP = /^[A-ZА-ЯЁ0-9]/

/**
 * Имя бизнеса.
 * 1. В кавычках — берём как есть: «Борода».
 * 2. Без кавычек отрезаем адрес («… на Ленина», «… в Нижнем») и хвост после запятой или тире.
 * 3. Если в конце идут слова с большой буквы, а первое слово — описание («Кофейня Уют»,
 *    «ногтевая студия Лак»), имя — эти слова: «Уют», «Лак». Иначе — вся фраза («Юрист по банкротству»).
 */
export function extractName(text: string): { name: string; quoted: boolean } {
  const q = text.match(/[«"“„]([^»"”“]{1,40})[»"”“]?/)
  if (q) return { name: fit(q[1]), quoted: true }

  let raw = text.split(/[,;(]|\s[—–-]\s/)[0].trim().replace(/\s+/g, ' ')
  raw = raw
    .replace(/\s(на|в|во)\s(улиц[еы]|ул\.?|проспекте|пр-те|пр\.|площади|переулке|бульваре|шоссе|набережной|районе|ТЦ|ТРЦ|центре)(\s|$).*$/iu, '')
    .replace(/\s(на|в|во|у|возле|около|рядом с)\s[A-ZА-ЯЁ].*$/u, '')
    .trim()
  if (!raw) return { name: '', quoted: false }

  const words = raw.split(' ')
  let i = words.length
  while (i > 1 && CAP.test(words[i - 1])) i--
  const tail = words.slice(i)
  // «Мастерская Сергея Петровича», «Автомастерская Константинопольского» — это не бренд, а часть фразы
  const genitive = tail.length > 0 && (/(ого|его)$/u.test(tail[0]) || /(вич|вича|вны|ична|ичны)$/u.test(tail[tail.length - 1]))
  if (i > 0 && i < words.length && !genitive) return { name: fit(tail.join(' ')), quoted: true }
  return { name: fit(raw), quoted: false }
}

/** Не длиннее 34 знаков, только по границе слова (длинное первое слово целиком), без висящего предлога в конце */
function fit(s: string): string {
  let raw = s.trim().replace(/\s+/g, ' ')
  if (raw.length > 34) {
    const words = raw.split(' ')
    let out = words[0]
    for (const w of words.slice(1)) {
      if ((out + ' ' + w).length > 34) break
      out += ' ' + w
    }
    raw = out.replace(/\s+\S{1,3}$/u, '')
  }
  return raw.charAt(0).toUpperCase() + raw.slice(1)
}

const TR: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z', и: 'i', й: 'y', к: 'k',
  л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts',
  ч: 'ch', ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
}

const STOP = new Set(['na', 'v', 'vo', 'u', 's', 'so', 'k', 'po', 'za', 'do', 'ot', 'i', 'iz', 'dlya', 'pod', 'pro'])

/** «Борода» → boroda.ru, «Кофейня Уют на Ленина» → kofeynya-uyut.ru. Для адресной строки превью */
export function toDomain(name: string): string {
  const words = name
    .toLowerCase()
    .replace(/…/g, '')
    .split('')
    .map((c) => TR[c] ?? c)
    .join('')
    .split(/[^a-z0-9]+/)
    .filter((w) => w && !STOP.has(w))
  let out = ''
  for (const w of words) {
    const next = out ? `${out}-${w}` : w
    if (next.length > 22) break
    out = next
  }
  return (out || words[0]?.slice(0, 22) || 'vash-biznes') + '.ru'
}

export interface Draft {
  name: string
  /** Имя пришло в кавычках: показываем «Борода». Иначе — как написали */
  quoted: boolean
  niche: Niche
  domain: string
  /** Подпись над заголовком: «барбершоп «Борода»», а если ниша уже в имени — просто имя */
  label: string
}

export function makeDraft(text: string, sphere: SphereId | null): Draft {
  const found = detectNiche(text)
  const niche =
    found && (!sphere || found.sphere === sphere)
      ? found
      : nicheById(SPHERES.find((s) => s.id === sphere)?.fallback ?? 'generic')
  const got = extractName(text)
  const name = got.name || niche.sample.replace(/^.*«|»$/g, '')
  const quoted = got.name ? got.quoted : true
  const stem = niche.noun.toLowerCase().slice(0, 5)
  const label = !quoted || name.toLowerCase().includes(stem) ? name : `${niche.noun} «${name}»`
  return { name, quoted, niche, domain: toDomain(name), label }
}

